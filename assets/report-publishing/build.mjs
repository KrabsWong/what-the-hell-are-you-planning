// Only public report assets enter the EdgeOne deployment artifact.
import { readdir, lstat, mkdir, copyFile, rm } from 'node:fs/promises';
import path from 'node:path';
const output = 'report-public';
const marker = '.planning-report-output';
// Refuse an existing non-generated directory rather than deleting repository content.
try {
  const entries = await readdir(output);
  if (!entries.includes(marker)) throw new Error('report-public already exists and is not generated by Planning');
  await rm(output, { recursive: true });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
await mkdir(output);
const { writeFile } = await import('node:fs/promises');
await writeFile(path.join(output, marker), 'Planning generated output\n');
async function copy(source, destination) {
  const stat = await lstat(source);
  if (stat.isSymbolicLink()) throw new Error(`Public assets cannot contain symbolic links: ${source}`);
  if (stat.isDirectory()) {
    await mkdir(destination, { recursive: true });
    for (const name of await readdir(source)) await copy(path.join(source, name), path.join(destination, name));
  } else if (stat.isFile()) {
    await copyFile(source, destination);
  } else throw new Error(`Unsupported public asset: ${source}`);
}
for (const name of await readdir('.')) {
  if (['index.html', '404.html', 'robots.txt', 'favicon.ico', 'assets'].includes(name) || /^[a-f0-9]{32}$/.test(name)) {
    await copy(name, path.join(output, name));
  }
}
